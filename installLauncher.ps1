param([switch]$Remove, [string]$Target = (Join-Path $HOME '.local\bin'), [switch]$NoPath)
# Installs bare commands that forward to this checkout:
#   OpenClaude.cmd            -> routing session
#   OpenClaudeDashboard.cmd   -> dashboard
#   startOpenClaude.cmd, startDashboard.cmd,
#   startClaudeOpenRouter.cmd, startClaudeDashboard.cmd  -> forwarders for previous names
#   .\installLauncher.ps1          # install or refresh (adds the default folder to the user PATH)
#   .\installLauncher.cmd          # same, from a shell that blocks unsigned scripts
#   .\installLauncher.ps1 -Remove  # delete every installed forwarder
#   .\installLauncher.ps1 -NoPath  # install the forwarders but do not touch the user PATH
#
# The forwarders are .cmd on purpose: cmd.exe is not subject to the PowerShell execution
# policy, and each one re-launches PowerShell with -ExecutionPolicy Bypass. Unsigned .ps1
# forwarders failed on every new terminal whose effective policy was AllSigned, which is
# exactly what this installer must not depend on. Legacy generated .ps1 forwarders are
# replaced on upgrade so PowerShell stops preferring them over the .cmd version.
$ErrorActionPreference = 'Stop'
$marker = '# Generated by installLauncher.ps1'

$commands = [ordered]@{
    'OpenClaude.cmd'            = @('OpenClaude.ps1', 'routing session')
    'OpenClaudeDashboard.cmd'   = @('OpenClaudeDashboard.ps1', 'dashboard')
    'startOpenClaude.cmd'       = @('OpenClaude.ps1', 'previous name')
    'startDashboard.cmd'        = @('OpenClaudeDashboard.ps1', 'previous name')
    'startClaudeOpenRouter.cmd' = @('OpenClaude.ps1', 'previous name')
    'startClaudeDashboard.cmd'  = @('OpenClaudeDashboard.ps1', 'previous name')
}
# Forwarders written by earlier versions; a .ps1 with the same base name would win command
# resolution in PowerShell, so they are removed during install and -Remove.
$legacyNames = [ordered]@{
    'OpenClaude.ps1'            = @('OpenClaude.ps1', 'routing session')
    'OpenClaudeDashboard.ps1'   = @('OpenClaudeDashboard.ps1', 'dashboard')
    'startOpenClaude.ps1'       = @('OpenClaude.ps1', 'previous name')
    'startDashboard.ps1'        = @('OpenClaudeDashboard.ps1', 'previous name')
    'startClaudeOpenRouter.ps1' = @('OpenClaude.ps1', 'previous name')
    'startClaudeDashboard.ps1'  = @('OpenClaudeDashboard.ps1', 'previous name')
}

function Resolve-Directory([string]$path) {
    return [System.IO.Path]::GetFullPath($path).TrimEnd('\', '/')
}

# Batch files are read by cmd.exe with the OEM code page, not UTF-8. The checkout path is
# embedded in the file, so write and compare using the same encoding.
function Get-BatchEncoding() {
    return [System.Text.Encoding]::GetEncoding([System.Globalization.CultureInfo]::CurrentCulture.TextInfo.OEMCodePage)
}

$origin = Resolve-Directory $PSScriptRoot
$destination = Resolve-Directory $Target
if ($destination -eq $origin) {
    throw "-Target must not be this checkout ($origin): installing there would overwrite the scripts it forwards to."
}

function Get-ForwarderBody([string]$targetScript, [string]$label) {
    $raw = Join-Path $PSScriptRoot $targetScript
    # % and ^ are special in batch files even inside the path string.
    $quoted = $raw.Replace('%', '%%')
    return @(
        "@echo off",
        "rem $marker - $label, forwards to the checkout.",
        "setlocal",
        'set "CLAUDE_CHEAT_PS=powershell.exe"',
        'where pwsh.exe >nul 2>nul && set "CLAUDE_CHEAT_PS=pwsh.exe"',
        """%CLAUDE_CHEAT_PS%"" -NoProfile -ExecutionPolicy Bypass -File ""$quoted"" %*",
        "exit /b %ERRORLEVEL%"
    )
}

function Get-ExpectedBytes([string]$targetScript, [string]$label) {
    $text = ((Get-ForwarderBody $targetScript $label) -join "`r`n") + "`r`n"
    return (Get-BatchEncoding).GetBytes($text)
}

function Test-Forwarder([string]$path, [string]$targetScript, [string]$label) {
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { return $false }
    try { $actual = [System.IO.File]::ReadAllBytes($path) }
    catch { return $false }
    $expected = Get-ExpectedBytes $targetScript $label
    if ($actual.Length -ne $expected.Length) { return $false }
    for ($i = 0; $i -lt $expected.Length; $i++) {
        if ($actual[$i] -ne $expected[$i]) { return $false }
    }
    return $true
}

function Test-LegacyForwarder([string]$path) {
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { return $false }
    try { $first = Get-Content -LiteralPath $path -TotalCount 1 -ErrorAction Stop }
    catch { return $false }
    return ($null -ne $first) -and ($first -like "$marker*")
}

function Remove-LegacyForwarders() {
    foreach ($name in $legacyNames.Keys) {
        $path = Join-Path $destination $name
        if (-not (Test-LegacyForwarder $path)) { continue }
        Remove-Item -LiteralPath $path -Force
        Write-Host "removed legacy forwarder: $path"
    }
}

if ($Remove) {
    foreach ($name in $commands.Keys) {
        $path = Join-Path $destination $name
        if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { continue }
        if (-not (Test-Forwarder $path $commands[$name][0] $commands[$name][1])) {
            Write-Warning "kept $name (not created by this installer)"
            continue
        }
        Remove-Item -LiteralPath $path -Force
        Write-Host "removed $path"
    }
    Remove-LegacyForwarders
    return
}

if (-not (Test-Path -LiteralPath $destination)) {
    New-Item -ItemType Directory -Path $destination -Force | Out-Null
}

foreach ($name in $commands.Keys) {
    $targetScript, $label = $commands[$name]
    $resolved = Join-Path $PSScriptRoot $targetScript
    if (-not (Test-Path -LiteralPath $resolved)) {
        Write-Warning "$targetScript is missing beside this installer; skipped $name"
        continue
    }
    $path = Join-Path $destination $name
    if ((Test-Path -LiteralPath $path) -and -not (Test-Forwarder $path $targetScript $label)) {
        Write-Warning "kept $name (a file not created by this installer already exists)"
        continue
    }
    [System.IO.File]::WriteAllBytes($path, (Get-ExpectedBytes $targetScript $label))
    Write-Host "installed: $path"
}

Remove-LegacyForwarders

# Register the default install directory in the *user* PATH so a new terminal can run the bare
# command without editing Windows Environment Variables by hand. A custom -Target is never
# registered (the caller chose it deliberately), and -NoPath opts out.
function Add-UserPathEntry([string]$directory) {
    $entries = @([Environment]::GetEnvironmentVariable('Path', 'User') -split ';' | Where-Object { $_ })
    $normalized = $entries | ForEach-Object { $_.TrimEnd('\', '/') }
    if ($normalized -contains $directory) { return $false }
    $updated = (@($entries) + $directory) -join ';'
    [Environment]::SetEnvironmentVariable('Path', $updated, 'User')
    return $true
}

$defaultTarget = Resolve-Directory (Join-Path $HOME '.local\bin')
$onPath = ($env:PATH -split ';' | Where-Object { $_ } | ForEach-Object { $_.TrimEnd('\', '/') }) -contains $destination
if (-not $onPath -and $destination -eq $defaultTarget -and -not $NoPath) {
    if (Add-UserPathEntry $destination) {
        Write-Host "added to user PATH: $destination (open a new terminal to use it there)"
    }
    $env:PATH = ($env:PATH.TrimEnd(';') + ';' + $destination)
    $onPath = $true
}

if ($onPath) {
    Write-Host 'run from any folder:  OpenClaude   |   OpenClaudeDashboard'
} else {
    Write-Warning "$destination is not on PATH; add this directory to your user PATH using Windows Environment Variables settings."
}
