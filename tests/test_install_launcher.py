"""The launcher installer is verified end to end: install, forward, remove.

The forwarders are .cmd so they keep working in a terminal whose PowerShell execution
policy blocks unsigned .ps1 files; the installer must also clean up the older .ps1
forwarders, because PowerShell would otherwise resolve those first. Runs on Windows with
PowerShell and Node.js.
"""
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
POWERSHELL = shutil.which("pwsh") or shutil.which("powershell")
FORWARDERS = {
    "OpenClaude.cmd": "OpenClaude.ps1",
    "OpenClaudeDashboard.cmd": "OpenClaudeDashboard.ps1",
    "startOpenClaude.cmd": "OpenClaude.ps1",
    "startDashboard.cmd": "OpenClaudeDashboard.ps1",
    "startClaudeOpenRouter.cmd": "OpenClaude.ps1",
    "startClaudeDashboard.cmd": "OpenClaudeDashboard.ps1",
}
LEGACY_MARKER = "# Generated by installLauncher.ps1"


def decode_batch(path: Path) -> str:
    # Batch files are OEM-encoded; ASCII paths are identical in every Windows code page here.
    return path.read_bytes().decode("mbcs", errors="replace")


@unittest.skipUnless(os.name == "nt" and POWERSHELL, "Windows with PowerShell required")
class InstallLauncherTests(unittest.TestCase):
    def setUp(self):
        self.target = Path(self.enterContext(tempfile.TemporaryDirectory())) / "bin"

    def run_installer(self, *args):
        return subprocess.run([POWERSHELL, "-NoProfile", "-ExecutionPolicy", "Bypass",
                               "-File", str(ROOT / "installLauncher.ps1"), "-Target", str(self.target), *args],
                              cwd=str(ROOT), capture_output=True, text=True, timeout=120,
                              encoding="utf-8", errors="replace")

    def run_forwarder(self, name, *args, policy=None):
        command = [POWERSHELL, "-NoProfile"]
        if policy:
            command += ["-ExecutionPolicy", policy]
        command += ["-Command", f"& cmd /c '{self.target / name}' {' '.join(args)}; exit $LASTEXITCODE"]
        return subprocess.run(command, cwd=str(ROOT), capture_output=True, text=True, timeout=120,
                              encoding="utf-8", errors="replace")

    def test_install_writes_every_forwarder_to_the_target(self):
        result = self.run_installer()
        self.assertEqual(result.returncode, 0, result.stderr[-600:])
        for name, script in FORWARDERS.items():
            path = self.target / name
            with self.subTest(forwarder=name):
                self.assertTrue(path.is_file(), f"{name} was not created")
                body = decode_batch(path)
                self.assertIn(str(ROOT / script), body)
                self.assertIn("%*", body)
                self.assertIn("-ExecutionPolicy Bypass", body)

    def test_a_custom_target_never_rewrites_the_user_path(self):
        # Auto-registering the default folder must not leak into an explicit -Target install.
        probe = [POWERSHELL, "-NoProfile", "-Command",
                 "[Environment]::GetEnvironmentVariable('Path','User')"]
        before = subprocess.run(probe, capture_output=True, text=True, timeout=60,
                                encoding="utf-8", errors="replace").stdout
        result = self.run_installer()
        self.assertEqual(result.returncode, 0, result.stderr[-600:])
        after = subprocess.run(probe, capture_output=True, text=True, timeout=60,
                               encoding="utf-8", errors="replace").stdout
        self.assertEqual(before, after)
        self.assertNotIn(str(self.target), after)

    def test_forwarder_reaches_the_real_script(self):
        self.assertEqual(self.run_installer().returncode, 0)
        # An invalid provider is rejected by the target script's ValidateSet, which proves
        # the arguments travel through the forwarder without starting a session.
        result = self.run_forwarder("OpenClaude.cmd", "-Provider", "Nope")
        self.assertNotEqual(result.returncode, 0)
        combined = result.stdout + result.stderr
        self.assertIn("Provider", combined)
        self.assertIn("ValidateSet", combined)

    def test_forwarder_ignores_an_all_signed_execution_policy(self):
        self.assertEqual(self.run_installer().returncode, 0)
        result = self.run_forwarder("OpenClaude.cmd", "-Provider", "Nope", policy="AllSigned")
        self.assertNotEqual(result.returncode, 0, "the forwarder must reach the launcher, not fail on policy")
        combined = result.stdout + result.stderr
        self.assertIn("ValidateSet", combined)
        self.assertNotIn("not digitally signed", combined)
        self.assertNotIn("디지털 서명", combined)

    def test_remove_deletes_every_forwarder(self):
        self.assertEqual(self.run_installer().returncode, 0)
        for name in FORWARDERS:
            self.assertTrue((self.target / name).is_file())
        result = self.run_installer("-Remove")
        self.assertEqual(result.returncode, 0, result.stderr[-600:])
        remaining = [name for name in FORWARDERS if (self.target / name).exists()]
        self.assertEqual(remaining, [])

    def test_legacy_ps1_forwarders_are_replaced(self):
        self.target.mkdir(parents=True, exist_ok=True)
        legacy = self.target / "OpenClaude.ps1"
        legacy.write_text(f"{LEGACY_MARKER} - routing session, forwards to the checkout.\nexit 0\n",
                          encoding="utf-8")
        foreign = self.target / "startDashboard.ps1"
        foreign.write_text("# mine\n", encoding="utf-8")
        result = self.run_installer()
        self.assertEqual(result.returncode, 0, result.stderr[-600:])
        self.assertFalse(legacy.exists(), "an unsigned .ps1 with the same name would win in PowerShell")
        self.assertTrue(foreign.exists(), "a user file must survive the upgrade")
        self.assertEqual(self.run_installer("-Remove").returncode, 0)
        self.assertTrue(foreign.exists(), "a user file must survive -Remove")

    def test_repository_cmd_entry_point_bypasses_policy(self):
        # The checkout itself is usable from a policy-restricted terminal without installing.
        entry = ROOT / "OpenClaude.cmd"
        self.assertTrue(entry.is_file())
        result = subprocess.run([POWERSHELL, "-NoProfile", "-ExecutionPolicy", "AllSigned", "-Command",
                                 f"& cmd /c '{entry}' -Provider Nope; exit $LASTEXITCODE"],
                                cwd=str(ROOT), capture_output=True, text=True, timeout=120,
                                encoding="utf-8", errors="replace")
        self.assertNotEqual(result.returncode, 0)
        combined = result.stdout + result.stderr
        self.assertIn("ValidateSet", combined)
        self.assertNotIn("디지털 서명", combined)
        self.assertNotIn("not digitally signed", combined)

    def test_target_may_not_be_the_checkout(self):
        # Writing forwarders over the scripts they forward to would recurse forever and
        # let -Remove delete the sources.
        result = subprocess.run([POWERSHELL, "-NoProfile", "-ExecutionPolicy", "Bypass",
                                 "-File", str(ROOT / "installLauncher.ps1"), "-Target", str(ROOT)],
                                cwd=str(ROOT), capture_output=True, text=True, timeout=120,
                                encoding="utf-8", errors="replace")
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("must not be this checkout", result.stdout + result.stderr)
        self.assertIn("param([ValidateSet", (ROOT / "OpenClaude.ps1").read_text(encoding="utf-8-sig"))

    def test_a_foreign_file_is_never_overwritten_or_removed(self):
        self.target.mkdir(parents=True, exist_ok=True)
        foreign = self.target / "OpenClaude.cmd"
        original = b"@echo mine\r\n"
        foreign.write_bytes(original)
        result = self.run_installer()
        self.assertEqual(result.returncode, 0, result.stderr[-400:])
        self.assertEqual(foreign.read_bytes(), original)
        self.assertIn("kept OpenClaude.cmd", result.stdout + result.stderr)
        removed = self.run_installer("-Remove")
        self.assertEqual(removed.returncode, 0, removed.stderr[-400:])
        self.assertTrue(foreign.exists(), "a user file must survive -Remove")

    def test_modified_generated_forwarder_is_preserved(self):
        self.assertEqual(self.run_installer().returncode, 0)
        path = self.target / "OpenClaude.cmd"
        modified = decode_batch(path) + "rem user change\r\n"
        path.write_bytes(modified.encode("mbcs"))
        self.assertEqual(self.run_installer().returncode, 0)
        self.assertEqual(decode_batch(path), modified)
        self.assertEqual(self.run_installer("-Remove").returncode, 0)
        self.assertEqual(decode_batch(path), modified)

    def test_install_is_idempotent(self):
        self.assertEqual(self.run_installer().returncode, 0)
        first = (self.target / "OpenClaude.cmd").read_bytes()
        self.assertEqual(self.run_installer().returncode, 0)
        self.assertEqual((self.target / "OpenClaude.cmd").read_bytes(), first)


if __name__ == "__main__":
    unittest.main()
